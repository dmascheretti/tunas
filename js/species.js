/** Peso stimato (kg) dalla lunghezza alla forca (cm). */
export function weightFromLength(species, cm) {
  const { a, b } = species.lw;
  return a * Math.pow(cm, b);
}

/** Lunghezza (cm) corrispondente a un peso (kg). */
export function lengthFromWeight(species, kg) {
  const { a, b } = species.lw;
  return Math.pow(kg / a, 1 / b);
}
